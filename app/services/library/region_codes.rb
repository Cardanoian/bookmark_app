    # 학교의 정보나루 시도 코드. region(교육청명) 우선, 실패/공란 시 address 첫 토큰 폴백, 그래도 nil.
    def for_school(school)
      return nil if school.nil?

      for_office(school.region) || for_address(school.address)
    end

    # 교육청명 → 코드(미지값 nil).
    def for_office(region)
      SIDO_BY_OFFICE[region.to_s.strip]
    end

    # 도로명주소 첫 토큰(시도명) → 코드(미지값 nil).
    def for_address(address)
      first_token = address.to_s.strip.split(/\s+/).first
      SIDO_BY_ADDRESS[first_token.to_s]
    end
